// Transforms the owner's mattress specs CSV (workspace/owner/*-mattress-specs.csv) into a typed module. Pure data transform:
// no copy is written here, and every value comes from the CSV unchanged.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
// The owner files stay local (workspace/owner is not committed); locate the specs CSV by suffix.
const ownerDir = path.join(root, 'workspace', 'owner');
const specsFile = (await readdir(ownerDir)).find(f => f.endsWith('-mattress-specs.csv'));
if (!specsFile) throw new Error('No *-mattress-specs.csv in workspace/owner.');
const source = path.join(ownerDir, specsFile);
const target = path.join(root, 'src', 'data', 'specs.generated.ts');

const parseLine = (line) => {
  const out = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { cell += '"'; i += 1; }
      else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { out.push(cell); cell = ''; }
    else cell += ch;
  }
  out.push(cell);
  return out;
};

const FAIL = 'FAIL: page not reachable';
const NOT_LISTED = 'not listed';
const list = (value) => (value === NOT_LISTED || value === FAIL ? [] : value.split(';').map(item => item.trim()).filter(Boolean));
const numbers = (value) => (value.match(/\d+(?:\.\d+)?/g) ?? []).map(Number);

// "Plush 4-5" -> { label: 'Plush', value: 4, display: '4-5' }; a range is treated as its lower number.
const firmness = (value) => list(value).map((option) => {
  const match = option.match(/^(.*?)\s*(\d+(?:\.\d+)?(?:-\d+(?:\.\d+)?)?)$/);
  if (!match) return { label: option, value: null, display: null };
  return { label: match[1].trim(), value: Number(match[2].split('-')[0]), display: match[2] };
});

const layers = (value) => list(value.replace(/ \/ /g, '; ')).map((layer) => {
  const index = layer.lastIndexOf(':');
  return index === -1
    ? { name: layer, thickness: NOT_LISTED }
    : { name: layer.slice(0, index).trim(), thickness: layer.slice(index + 1).trim() };
});

const lines = (await readFile(source, 'utf8')).trim().split(/\r?\n/);
const header = parseLine(lines[0]);
const records = lines.slice(1).map((line) => Object.fromEntries(parseLine(line).map((cell, i) => [header[i], cell])));

const specs = Object.fromEntries(records.map((r) => {
  const reachable = r.type !== FAIL;
  return [r.slug, {
    slug: r.slug,
    model: r.model,
    reachable,
    type: reachable ? r.type : null,
    construction: reachable ? list(r.construction) : [],
    firmnessRaw: r.firmness_options,
    firmnessOptions: reachable ? firmness(r.firmness_options) : [],
    heightRaw: r.height_in,
    heightsIn: reachable && r.height_in !== NOT_LISTED ? numbers(r.height_in) : [],
    layersRaw: r.layers,
    layers: reachable ? layers(r.layers) : [],
    queenPriceRaw: r.queen_price_usd,
    queenPricesUsd: reachable && r.queen_price_usd !== NOT_LISTED ? numbers(r.queen_price_usd) : [],
    priceChecked: r.price_checked,
    trialNights: reachable && r.trial_nights !== NOT_LISTED ? Number(r.trial_nights) : null,
    warranty: r.warranty_years,
    shipping: r.shipping,
    returns: r.returns,
    sizes: list(r.sizes),
    certifications: list(r.certifications),
    organicCert: r.organic_cert,
    madeIn: r.made_in,
    productUrl: r.product_url,
    sourceChecked: r.source_checked,
  }];
}));

const body = `// GENERATED by scripts/generate-owner-data.mjs from the owner's mattress specs CSV. Do not edit by hand.
import type { MattressSpec } from './specTypes';

export const SPECS: Record<string, MattressSpec> = ${JSON.stringify(specs, null, 2)};
`;
await writeFile(target, body, 'utf8');
console.log(`Wrote ${Object.keys(specs).length} spec records to ${path.relative(root, target)}.`);

// The owner page map: every URL with its page type, H1, ranking row, and action.
const mapSource = path.join(root, 'workspace', 'owner', 'mattressinquirer-page-map.csv');
const mapTarget = path.join(root, 'src', 'data', 'pageMap.generated.ts');
const mapLines = (await readFile(mapSource, 'utf8')).trim().split(/\r?\n/);
const mapHeader = parseLine(mapLines[0]);
const mapRows = mapLines.slice(1)
  .map((line) => Object.fromEntries(parseLine(line).map((cell, i) => [mapHeader[i], cell])))
  .filter((row) => row.url.startsWith('/'))
  .map((row) => ({ url: row.url, pageType: row.page_type, h1: row.h1, rankingRow: row.ranking_row, action: row.phase1_action, notes: row.notes }));
await writeFile(mapTarget, `// GENERATED by scripts/generate-owner-data.mjs from workspace/owner/mattressinquirer-page-map.csv. Do not edit by hand.
export interface PageMapRow { url: string; pageType: string; h1: string; rankingRow: string; action: string; notes: string }

export const PAGE_MAP: PageMapRow[] = ${JSON.stringify(mapRows, null, 2)};
`, 'utf8');
console.log(`Wrote ${mapRows.length} page-map rows to ${path.relative(root, mapTarget)}.`);
